# PlatformIO pre-build script (SPEC_v3 §4.6): gzips every file in web/ and
# embeds it in the firmware as src/generated/web_assets.h, so an OTA
# firmware update also updates the UI and config.json is never touched.

import gzip
import hashlib
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".json": "application/json",
    ".png": "image/png",
    ".ico": "image/x-icon",
}

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
web_dir = os.path.join(project_dir, "web")
out_dir = os.path.join(project_dir, "src", "generated")
out_file = os.path.join(out_dir, "web_assets.h")


def c_name(path):
    return "asset_" + "".join(ch if ch.isalnum() else "_" for ch in path)


def build():
    files = []
    for root, _, names in os.walk(web_dir):
        for name in sorted(names):
            if name.startswith("."):
                continue
            full = os.path.join(root, name)
            rel = os.path.relpath(full, web_dir).replace(os.sep, "/")
            ext = os.path.splitext(name)[1].lower()
            if ext not in MIME:
                continue
            with open(full, "rb") as f:
                raw = f.read()
            # mtime=0 keeps the output (and the ETag) identical for identical input
            files.append((rel, MIME[ext], gzip.compress(raw, 9, mtime=0), len(raw)))
    files.sort()

    digest = hashlib.sha1()
    for rel, _, data, _ in files:
        digest.update(rel.encode())
        digest.update(data)
    etag = digest.hexdigest()[:16]

    lines = [
        "// Generated by scripts/embed_web.py from web/. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace drinkbot {",
        "",
        "struct WebAsset {",
        "  const char* path;  // served at \"/\" + path",
        "  const char* mime;",
        "  const uint8_t* data;  // gzip",
        "  size_t length;",
        "};",
        "",
        'constexpr const char* kWebAssetsEtag = "\\"%s\\"";' % etag,
        "",
    ]
    total = 0
    for rel, _, data, _ in files:
        total += len(data)
        body = ",".join(str(b) for b in data)
        lines.append("const uint8_t %s[] = {%s};" % (c_name(rel), body))
    lines.append("")
    lines.append("const WebAsset kWebAssets[] = {")
    for rel, mime, data, _ in files:
        lines.append('    {"%s", "%s", %s, %d},' % (rel, mime, c_name(rel), len(data)))
    lines.append("};")
    lines.append("constexpr size_t kWebAssetCount = %d;" % len(files))
    lines.append("")
    lines.append("}  // namespace drinkbot")
    text = "\n".join(lines) + "\n"

    os.makedirs(out_dir, exist_ok=True)
    old = None
    if os.path.exists(out_file):
        with open(out_file) as f:
            old = f.read()
    if old != text:  # leave the file alone when nothing changed, so it isn't rebuilt
        with open(out_file, "w") as f:
            f.write(text)
    print("embed_web: %d files, %d bytes gzipped, etag %s" % (len(files), total, etag))


build()
